def _field(
    key: str,
    label: str,
    field_type: FieldType,
    *,
    unit: str | None = None,
    internal: bool = False,
    computed: bool = False,
    options_key: str | None = None,
) -> dict[str, Any]:
    return {
        "key": key,
        "label": label,
        "type": field_type,
        "unit": unit,
        "internal": internal,
        "computed": computed,
        "options_key": options_key or (key if field_type == "select" else None),
    }


